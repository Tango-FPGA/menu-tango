// tango_test_pattern -- Tango's background: the test pattern, per pixel from the
// HDMI beam counters.  No framebuffer, no ROM, no BSRAM, no multiplier, no divider.
//
// SPEC = the test pattern's reference model, test_pattern() of the Tango
// menu's Python renderer.  Every constant below is that model's, cited by
// name; a simulated frame of this module equals the model's 1280x720
// picture pixel for pixel.
//
// Beam interface = hdl-util hdmi.sv (sys/hdmi/hdmi.sv): cx/cy name
// "the pixel to be generated by the user in THIS clock and sent out in the NEXT
// clock", so rgb is registered from (cx, cy).  720p VIC 4: cx 0..1649, cy 0..749, visible 1280x720
// (hdmi.sv frame_width 1650 / frame_height 750).  hdmi.sv wraps cx after 1649.
//
// Structure (line-ahead precompute, all integer add/compare):
//   * PREP: during line cy the per-line state for line pl = cy+1 is prepared
//     (gradient accumulators, y mod 40/160, sweep distance, the two ring
//     half-width trackers).  At cx == 1649 (last clock of the line) prep is
//     committed to CUR, which is then constant for the whole next line.
//     prep state restarts at pl == 0 every frame, so any reset transient heals
//     by the next frame.
//   * PIXEL: one registered stage from cx + CUR registers + x counters.
//
// Rings (model _circle_spans + the fill-between-lines rule):  for a line with
// a = |y - 360| <= r, the model takes hw = isqrt(r^2 - a^2) and hp = the
// half-width of the neighbouring line toward the centre (y-1 below, y+1 above
// and at the centre), i.e. with a' = max(a,1): lo = f(a'), hi = f(a'-1),
// f(n) = isqrt(r^2 - n^2), and the pixel is on the ring if lo-1 <= |x-640| <= hi+1.
// f() is tracked incrementally (no isqrt, no multiply): each tracker holds
// n, T = r^2 - n^2, h, h^2 and walks one step per clock:
//     n -> n+1 : T -= 2n+1          n -> n-1 : T += 2n-1
//     (h+1)^2 <= T : h += 1, h^2 += 2h+1      h^2 > T : h -= 1, h^2 -= 2h-1
// Worst walk per line is 24 steps (a = r -> r-1 at r = 300); a line is 1650 clocks.
//==============================================================================
`default_nettype none
module tango_test_pattern #(
    // accent = the launcher's Menu colour; the model's test_pattern(accent=(242,163,58))
    parameter [7:0] ACC_R = 8'd242,
    parameter [7:0] ACC_G = 8'd163,
    parameter [7:0] ACC_B = 8'd58
) (
    input  wire        clk,         // clk_pix, 74.25 MHz
    input  wire        rst,         // same reset as hdmi.sv (holds cx = cy = 0)
    input  wire [11:0] cx,          // hdmi.sv beam counters
    input  wire [10:0] cy,
    output reg  [23:0] rgb = 24'd0  // {R,G,B} for (cx,cy) of the previous clock
);
    // ---- geometry (the model: W, H = 1280, 720; cx, cy = W//2, H//2) ----
    localparam integer W = 1280, H = 720;
    localparam integer XC = W / 2, YC = H / 2;        // 640, 360
    localparam integer LAST_X = 1649, LAST_Y = 749;   // hdmi.sv 720p frame_width-1 / frame_height-1
    localparam integer R1 = 300, R2 = 150;            // rings (300, 150)

    // ---- colours (the model's BG0 BG1 MINOR MAJOR RING BARS) ----
    localparam [7:0] BG0_R = 8'd9,  BG0_G = 8'd12, BG0_B = 8'd20;
    localparam [7:0] BG1_R = 8'd16, BG1_G = 8'd21, BG1_B = 8'd34;
    localparam [23:0] MINOR = {8'd22, 8'd29, 8'd45};
    localparam [23:0] MAJOR = {8'd36, 8'd46, 8'd70};
    localparam [23:0] RING  = {8'd58, 8'd72, 8'd104};
    localparam [23:0] ACCENT = {ACC_R, ACC_G, ACC_B};
    function [23:0] bar_rgb(input [2:0] i);
        case (i)
            3'd0: bar_rgb = {8'd232, 8'd236, 8'd244};
            3'd1: bar_rgb = {8'd242, 8'd224, 8'd74};
            3'd2: bar_rgb = {8'd63,  8'd208, 8'd224};
            3'd3: bar_rgb = {8'd79,  8'd208, 8'd138};
            3'd4: bar_rgb = {8'd217, 8'd91,  8'd217};
            3'd5: bar_rgb = {8'd229, 8'd72,  8'd77};
            3'd6: bar_rgb = {8'd74,  8'd123, 8'd255};
            default: bar_rgb = {8'd18, 8'd20, 8'd28};
        endcase
    endfunction
    // accent ramp: accent[k]*(t+1) >> 3, t = 0..7.  Constant table (elaboration-
    // time arithmetic on parameters only -- no hardware multiply).
    function [7:0] amul8(input [7:0] c, input integer k);
        amul8 = (c * k) >> 3;
    endfunction
    function [23:0] ramp_rgb(input [2:0] t);
        case (t)
            3'd0: ramp_rgb = {amul8(ACC_R,1), amul8(ACC_G,1), amul8(ACC_B,1)};
            3'd1: ramp_rgb = {amul8(ACC_R,2), amul8(ACC_G,2), amul8(ACC_B,2)};
            3'd2: ramp_rgb = {amul8(ACC_R,3), amul8(ACC_G,3), amul8(ACC_B,3)};
            3'd3: ramp_rgb = {amul8(ACC_R,4), amul8(ACC_G,4), amul8(ACC_B,4)};
            3'd4: ramp_rgb = {amul8(ACC_R,5), amul8(ACC_G,5), amul8(ACC_B,5)};
            3'd5: ramp_rgb = {amul8(ACC_R,6), amul8(ACC_G,6), amul8(ACC_B,6)};
            3'd6: ramp_rgb = {amul8(ACC_R,7), amul8(ACC_G,7), amul8(ACC_B,7)};
            default: ramp_rgb = ACCENT;          // accent*8>>3
        endcase
    endfunction
    // sweep tail: (accent[k]>>3) * a // 2, a = 6-d = 1..6 (constant table)
    function [7:0] tail8(input [7:0] c, input integer a);
        tail8 = ((c >> 3) * a) >> 1;
    endfunction
    function [23:0] tail_rgb(input [2:0] d);   // d = 0..5 -> a = 6..1
        case (d)
            3'd0: tail_rgb = {tail8(ACC_R,6), tail8(ACC_G,6), tail8(ACC_B,6)};
            3'd1: tail_rgb = {tail8(ACC_R,5), tail8(ACC_G,5), tail8(ACC_B,5)};
            3'd2: tail_rgb = {tail8(ACC_R,4), tail8(ACC_G,4), tail8(ACC_B,4)};
            3'd3: tail_rgb = {tail8(ACC_R,3), tail8(ACC_G,3), tail8(ACC_B,3)};
            3'd4: tail_rgb = {tail8(ACC_R,2), tail8(ACC_G,2), tail8(ACC_B,2)};
            default: tail_rgb = {tail8(ACC_R,1), tail8(ACC_G,1), tail8(ACC_B,1)};
        endcase
    endfunction

    // ======================= PREP (line pl = cy+1) =========================
    wire commit = (cx == LAST_X);
    // prep line index, derived from cy (never drifts): pl = cy+1 during line cy
    wire [10:0] pl      = (cy == LAST_Y) ? 11'd0 : cy + 11'd1;
    // line index prepared next (after this commit): cy+2 mod 750
    wire [10:0] pl_next = (cy == LAST_Y - 1) ? 11'd0 : (cy == LAST_Y) ? 11'd1 : cy + 11'd2;
    wire        new_frame = (pl_next == 11'd0);

    // vertical gradient BG0 + (BG1-BG0)*y // H: per-line accumulator (rem += delta,
    // carry at H).  delta < H so at most one carry per line.
    localparam [9:0] DG_R = BG1_R - BG0_R, DG_G = BG1_G - BG0_G, DG_B = BG1_B - BG0_B;
    reg [7:0] pg_r = 8'd0, pg_g = 8'd0, pg_b = 8'd0;
    reg [9:0] pa_r = 10'd0, pa_g = 10'd0, pa_b = 10'd0;
    wire [10:0] na_r = pa_r + DG_R, na_g = pa_g + DG_G, na_b = pa_b + DG_B;
    // y % 40 and (y / 40) % 4  -> y%40==0, y%160==0
    reg [5:0] pym40 = 6'd0;  reg [1:0] pyq = 2'd0;
    // sweep: sweep = (frame*3) % H; d = (sweep - y) % H stepped per line
    reg [9:0] sweep = 10'd0;                  // sweep of the frame being prepared
    wire [9:0] sweep_n = (sweep >= H - 3) ? sweep + 10'd3 - H : sweep + 10'd3;
    reg [9:0] pd = 10'd0;

    // ---- ring half-width trackers (see header) ----
    // a = |pl - 360|, a' = max(a,1); A tracks n = min(a',r) -> lo, B tracks n-1 -> hi.
    wire [10:0] ady  = (pl >= YC) ? pl - YC : YC - pl;
    wire [10:0] adp  = (ady == 11'd0) ? 11'd1 : ady;
    wire [8:0]  n1a  = (adp > R1) ? R1[8:0] : adp[8:0];
    wire [8:0]  n2a  = (adp > R2) ? R2[8:0] : adp[8:0];
    wire [8:0]  h1lo, h1hi, h2lo, h2hi;
    tango_isqrt_track #(.R(R1)) u_t1lo (.clk(clk), .rst(rst), .tgt(n1a),        .h(h1lo));
    tango_isqrt_track #(.R(R1)) u_t1hi (.clk(clk), .rst(rst), .tgt(n1a - 9'd1), .h(h1hi));
    tango_isqrt_track #(.R(R2)) u_t2lo (.clk(clk), .rst(rst), .tgt(n2a),        .h(h2lo));
    tango_isqrt_track #(.R(R2)) u_t2hi (.clk(clk), .rst(rst), .tgt(n2a - 9'd1), .h(h2hi));
    // ring x-intervals for line pl: [XC-1-hi, XC-lom1] U [XC+lom1, XC+1+hi], lom1 = max(lo-1,0)
    wire [8:0]  l1m1 = (h1lo == 9'd0) ? 9'd0 : h1lo - 9'd1;
    wire [8:0]  l2m1 = (h2lo == 9'd0) ? 9'd0 : h2lo - 9'd1;

    // ======================= CUR (line cy) =================================
    reg [7:0]  cg_r = 8'd0, cg_g = 8'd0, cg_b = 8'd0;   // gradient
    reg        c_minor = 1'b0, c_major = 1'b0;          // y%40==0, y%160==0
    reg        c_xhair = 1'b0;                          // y in {359,360}
    reg        c_bars = 1'b0, c_grey = 1'b0, c_ramp = 1'b0;
    reg        c_ya = 1'b0, c_ya3 = 1'b0, c_tick = 1'b0;
    reg        c_vis = 1'b0;                            // y < 720
    reg        c_r1 = 1'b0, c_r2 = 1'b0;                // |y-360| <= r
    reg [10:0] r1l0 = 0, r1l1 = 0, r1r0 = 0, r1r1 = 0;
    reg [10:0] r2l0 = 0, r2l1 = 0, r2r0 = 0, r2r1 = 0;
    reg        c_tail = 1'b0;  reg [23:0] c_add = 24'd0; // sweep tail add for this line

    always @(posedge clk) begin
        if (rst) begin
            pg_r <= BG0_R; pg_g <= BG0_G; pg_b <= BG0_B;
            pa_r <= 10'd0; pa_g <= 10'd0; pa_b <= 10'd0;
            pym40 <= 6'd0; pyq <= 2'd0; sweep <= 10'd0; pd <= 10'd0;
        end else if (commit) begin
            // ---- CUR <= PREP (line pl) ----
            cg_r <= pg_r; cg_g <= pg_g; cg_b <= pg_b;
            c_minor <= (pym40 == 6'd0);
            c_major <= (pym40 == 6'd0) && (pyq == 2'd0);
            c_xhair <= (pl == YC - 1) || (pl == YC);
            c_vis   <= (pl < H);
            c_bars  <= (pl >= 11'd652) && (pl < 11'd692);   // model: 652 <= y < 692
            c_grey  <= (pl >= 11'd22)  && (pl < 11'd38);    // model: 22 <= y < 38
            c_ramp  <= (pl >= 11'd42)  && (pl < 11'd48);    // model: 42 <= y < 48
            // brackets: by = 48 (sy=+1) and H-49 = 671 (sy=-1); arms 40, thickness 3
            c_ya    <= ((pl >= 11'd48) && (pl < 11'd88)) || ((pl >= 11'd632) && (pl <= 11'd671));
            c_ya3   <= ((pl >= 11'd48) && (pl < 11'd51)) || ((pl >= 11'd669) && (pl <= 11'd671));
            c_tick  <= (pl >= 11'd330) && (pl < 11'd390);   // model: 330 <= y < 390
            c_r1    <= (ady <= R1);
            c_r2    <= (ady <= R2);
            r1l0 <= XC - 1 - h1hi;  r1l1 <= XC - l1m1;  r1r0 <= XC + l1m1;  r1r1 <= XC + 1 + h1hi;
            r2l0 <= XC - 1 - h2hi;  r2l1 <= XC - l2m1;  r2r0 <= XC + l2m1;  r2r1 <= XC + 1 + h2hi;
            c_tail  <= (pd < 10'd6);
            c_add   <= tail_rgb(pd[2:0]);
            // ---- PREP advances to pl_next ----
            if (new_frame) begin
                pg_r <= BG0_R; pg_g <= BG0_G; pg_b <= BG0_B;
                pa_r <= 10'd0; pa_g <= 10'd0; pa_b <= 10'd0;
                pym40 <= 6'd0; pyq <= 2'd0;
                sweep <= sweep_n; pd <= sweep_n;            // d(0) = sweep
            end else begin
                if (na_r >= H) begin pa_r <= na_r - H; pg_r <= pg_r + 8'd1; end else pa_r <= na_r[9:0];
                if (na_g >= H) begin pa_g <= na_g - H; pg_g <= pg_g + 8'd1; end else pa_g <= na_g[9:0];
                if (na_b >= H) begin pa_b <= na_b - H; pg_b <= pg_b + 8'd1; end else pa_b <= na_b[9:0];
                if (pym40 == 6'd39) begin pym40 <= 6'd0; pyq <= pyq + 2'd1; end
                else pym40 <= pym40 + 6'd1;
                pd <= (pd == 10'd0) ? H - 1 : pd - 10'd1;   // d(y+1) = (d(y) - 1) % H
            end
        end
    end

    // ======================= x counters (aligned to cx) ====================
    // value at the clock where cx = X: xm40 = X % 40, xq = (X/40) % 4,
    // m50/s: s = (X-240) // 50 for X in 240..1039 (grey step; bar = s>>1)
    reg [5:0] xm40 = 6'd0;  reg [1:0] xq = 2'd0;
    reg [5:0] m50 = 6'd0;   reg [3:0] s50 = 4'd0;
    always @(posedge clk) begin
        if (rst || commit) begin
            xm40 <= 6'd0; xq <= 2'd0;
        end else if (xm40 == 6'd39) begin
            xm40 <= 6'd0; xq <= xq + 2'd1;
        end else xm40 <= xm40 + 6'd1;
        if (cx == 12'd239) begin
            m50 <= 6'd0; s50 <= 4'd0;
        end else if (m50 == 6'd49) begin
            m50 <= 6'd0; s50 <= s50 + 4'd1;
        end else m50 <= m50 + 6'd1;
    end

    // ======================= PIXEL ==========================================
    wire [10:0] x = cx[10:0];
    // The x flags are registered one clock ahead, from the NEXT beam position (cxn; hdmi.sv wraps cx after LAST_X): they were the head of the
    // worst clk_pix path of a launcher build (cx -> comparators -> the colour mux -> the sweep adders -> rgb, -0.353 ns in one placement
    // of logic that met +0.277 ns in another).  The picture is unchanged: cx counts +1 per clock from 0 to
    // LAST_X (reset holds cx = 0, and the flags of x = 0 and x = 1 are the same), so the flag registered at one clock is the flag of the pixel at the next.
    wire [11:0] cxn = (cx == LAST_X) ? 12'd0 : cx + 12'd1;
    reg xvis = 1'b1, xband = 1'b0, xa = 1'b0, xa3 = 1'b0, xtick = 1'b0, xxhair = 1'b0;
    always @(posedge clk) begin
        xvis   <= (cxn < W);
        xband  <= (cxn >= 12'd240) && (cxn < 12'd1040);          // model: 240 <= x < 1040
        // bracket x: bx = 48 (sx=+1) and W-49 = 1231 (sx=-1)
        xa     <= ((cxn >= 12'd48) && (cxn < 12'd88))  || ((cxn >= 12'd1192) && (cxn <= 12'd1231));
        xa3    <= ((cxn >= 12'd48) && (cxn < 12'd51))  || ((cxn >= 12'd1229) && (cxn <= 12'd1231));
        xtick  <= (cxn == 12'd64) || (cxn == W - 65);              // model: x in (64, W-65)
        xxhair <= (cxn == XC - 1) || (cxn == XC);
    end
    // Ring hits registered one clock ahead, for the next pixel x+1 (timing: r1l0 -> rgb was the
    // worst clk_pix path of a launcher build, +0.077 ns).  CUR (c_r*, r*) changes at the line
    // commit (cx 1649), so only the hit for x = 0 of a new line is computed from the old line's
    // CUR -- and x = 0 is never on a ring (rings span x 339..941), so the picture is unchanged.
    wire [10:0] xn = x + 11'd1;
    reg ring1 = 1'b0, ring2 = 1'b0;
    always @(posedge clk) begin
        ring1 <= c_r1 && (((xn >= r1l0) && (xn <= r1l1)) || ((xn >= r1r0) && (xn <= r1r1)));
        ring2 <= c_r2 && (((xn >= r2l0) && (xn <= r2l1)) || ((xn >= r2r0) && (xn <= r2r1)));
    end

    reg [23:0] c;
    always @* begin
        c = {cg_r, cg_g, cg_b};                                        // gradient
        if (xm40 == 6'd0 || c_minor) c = MINOR;                        // x%40, y%40
        if ((xm40 == 6'd0 && xq == 2'd0) || c_major) c = MAJOR;        // x%160, y%160
        if (xxhair || c_xhair) c = RING;                               // centre crosshair
        if (ring1 || ring2) c = RING;                                  // rings
        if (xband) begin
            if (c_bars)      c = bar_rgb(s50[3:1]);                    // (x-240)//100
            else if (c_grey) c = {s50, s50, s50, s50, s50, s50};       // ((x-240)*16//800)*17
            else if (c_ramp) c = ramp_rgb(s50[3:1]);                   // t = (x-240)*8//800
        end
        if ((xa && c_ya3) || (c_ya && xa3)) c = ACCENT;                // corner brackets
        if (xtick && c_tick) c = MAJOR;                                // safe-area ticks
    end
    // sweep: min(255, c + (accent>>3)*a//2)
    wire [8:0] sr = c[23:16] + c_add[23:16];
    wire [8:0] sg = c[15:8]  + c_add[15:8];
    wire [8:0] sb = c[7:0]   + c_add[7:0];
    always @(posedge clk)
        if (!(xvis && c_vis)) rgb <= 24'd0;
        else if (c_tail) rgb <= {sr[8] ? 8'hFF : sr[7:0], sg[8] ? 8'hFF : sg[7:0], sb[8] ? 8'hFF : sb[7:0]};
        else rgb <= c;
endmodule

//------------------------------------------------------------------------------
// tango_isqrt_track -- h = isqrt(R*R - n*n), n walking toward tgt one step per
// clock, h converging one step per clock.  Adds/compares only.
//------------------------------------------------------------------------------
module tango_isqrt_track #(parameter integer R = 300) (
    input  wire       clk,
    input  wire       rst,
    input  wire [8:0] tgt,          // 0..R
    output reg  [8:0] h = 9'd0
);
    // tgt registered (timing: the cy -> tgt -> step cone failed
    // clk_pix by 0.35 ns once the beam came from tango_beam_lead).  One clock of extra
    // latency on a per-line target; the walk has the whole 1650-clock line to converge.
    reg [8:0]  tgt_q = R[8:0];
    always @(posedge clk) tgt_q <= tgt;
    reg [8:0]  n  = R[8:0];         // start at n = R: T = 0, h = 0 (consistent)
    reg [17:0] t  = 18'd0;          // R*R - n*n   (R*R = 90000 < 2^17)
    reg [17:0] hs = 18'd0;          // h*h
    wire [17:0] up = hs + {h, 1'b1};            // (h+1)^2 = h^2 + 2h + 1
    always @(posedge clk) begin
        if (rst) begin
            n <= R[8:0]; t <= 18'd0; h <= 9'd0; hs <= 18'd0;
        end else if (n < tgt_q) begin
            t <= t - {n, 1'b1};                  // T -= 2n+1
            n <= n + 9'd1;
        end else if (n > tgt_q) begin
            t <= t + {n, 1'b0} - 18'd1;          // T += 2n-1
            n <= n - 9'd1;
        end else if (up <= t) begin
            h <= h + 9'd1; hs <= up;
        end else if (hs > t) begin
            h <= h - 9'd1; hs <= hs - {h, 1'b0} + 18'd1;   // h^2 - (2h-1)
        end
    end
endmodule
`default_nettype wire
